create or replace function public.cw_preparar_os() returns trigger
language plpgsql security definer set search_path=public as $$
begin
  if auth.uid() is not null and not public.cw_acesso_org(new.organizacao_id) then raise exception 'Sem acesso ao empreendimento'; end if;
  if auth.uid() is not null and not public.tem_permissao_usuario('os_criar') then raise exception 'Sem permissão para criar ordem de serviço'; end if;
  new.criado_por:=coalesce(new.criado_por,auth.uid());
  if new.codigo is null then new.codigo:=public.cw_proximo_codigo(new.organizacao_id,'OS',coalesce(new.criado_em,now())::date); end if;
  return new;
end $$;
drop trigger if exists cw_preparar_os on public.ordens_servico;
create trigger cw_preparar_os before insert on public.ordens_servico for each row execute function public.cw_preparar_os();

create or replace function public.cw_gerar_os_solicitacao(p_solicitacao bigint)
returns public.ordens_servico language plpgsql security definer set search_path=public as $$
declare d public.demandas%rowtype; resultado public.ordens_servico%rowtype;
begin
  select * into d from public.demandas where id=p_solicitacao;
  if d.id is null or not public.cw_acesso_org(d.organizacao_id) or not public.tem_permissao_usuario('os_criar') then raise exception 'Solicitação não encontrada ou sem permissão'; end if;
  insert into public.ordens_servico(organizacao_id,solicitacao_id,titulo,natureza,prioridade,local,descricao,inicio_previsto,fim_previsto,criado_por)
  values(d.organizacao_id,d.id,d.titulo,coalesce(d.natureza,case when d.tipo_demanda='preventiva' then 'Preventiva' else 'Corretiva' end),d.prioridade,d.local,d.observacoes,
    coalesce(d.agendamento_em,d.prazo::timestamptz),coalesce(d.agendamento_em,d.prazo::timestamptz),auth.uid()) returning * into resultado;
  return resultado;
end $$;

create or replace function public.cw_concluir_os(p_os bigint,p_descricao text,p_observacoes text default null)
returns jsonb language plpgsql security definer set search_path=public as $$
declare os public.ordens_servico%rowtype; abertas integer; perguntar boolean:=false;
begin
  select * into os from public.ordens_servico where id=p_os for update;
  if os.id is null or not public.cw_acesso_org(os.organizacao_id) or not public.tem_permissao_usuario('os_concluir') then raise exception 'OS não encontrada ou sem permissão'; end if;
  if nullif(trim(p_descricao),'') is null then raise exception 'Informe a descrição da execução'; end if;
  update public.ordens_servico set status='Concluída',descricao_execucao=trim(p_descricao),observacoes_executor=nullif(trim(p_observacoes),''),fim_real=coalesce(fim_real,now()),concluido_em=now() where id=p_os;
  if os.solicitacao_id is not null then
    select count(*) into abertas from public.ordens_servico where solicitacao_id=os.solicitacao_id and id<>p_os and status not in ('Concluída','Cancelada');
    perguntar:=abertas=0;
  end if;
  return jsonb_build_object('ordem_servico_id',p_os,'solicitacao_id',os.solicitacao_id,'ultima_os',perguntar,'perguntar_finalizacao',perguntar);
end $$;

create or replace function public.cw_finalizar_solicitacao_por_os(p_solicitacao bigint,p_finalizar boolean)
returns void language plpgsql security definer set search_path=public as $$
declare d public.demandas%rowtype;
begin
  select * into d from public.demandas where id=p_solicitacao for update;
  if d.id is null or not public.cw_acesso_org(d.organizacao_id) or not public.tem_permissao_usuario('solicitacao_alterar_status') then raise exception 'Sem permissão'; end if;
  if exists(select 1 from public.ordens_servico where solicitacao_id=p_solicitacao and status not in ('Concluída','Cancelada')) then raise exception 'Existem ordens de serviço em aberto'; end if;
  if p_finalizar then update public.demandas set status='Concluído',finalizada_por_os=true where id=p_solicitacao; end if;
end $$;

create or replace function public.cw_registrar_aceite_os(p_os bigint,p_aceitar boolean,p_observacao text default null,p_avaliacao integer default null)
returns void language plpgsql security definer set search_path=public as $$
declare os public.ordens_servico%rowtype;
begin
  select * into os from public.ordens_servico where id=p_os for update;
  if os.id is null or not public.cw_acesso_org(os.organizacao_id) then raise exception 'OS não encontrada'; end if;
  if not (public.tem_permissao_usuario('os_aceitar') or exists(select 1 from public.demandas d where d.id=os.solicitacao_id and d.criado_por=auth.uid())) then raise exception 'Sem permissão para registrar aceite'; end if;
  if not p_aceitar and nullif(trim(p_observacao),'') is null then raise exception 'Informe o motivo da recusa'; end if;
  update public.ordens_servico set aceite_status=case when p_aceitar then 'aceito' else 'recusado' end,
    aceite_por=auth.uid(),aceite_em=now(),aceite_observacao=nullif(trim(p_observacao),''),avaliacao=case when p_aceitar then p_avaliacao else null end,
    status=case when p_aceitar then status else 'Em execução' end,concluido_em=case when p_aceitar then concluido_em else null end where id=p_os;
end $$;

create or replace function public.cw_gerar_os_programadas(p_data date default current_date)
returns integer language plpgsql security definer set search_path=public as $$
declare plano public.planos_manutencao%rowtype; total integer:=0;
begin
  if auth.uid() is not null and not public.cw_admin() then raise exception 'Rotina exclusiva da administração'; end if;
  for plano in select * from public.planos_manutencao p where p.ativo and p.proxima_execucao-p.antecedencia_dias<=p_data
  loop
    if not exists(select 1 from public.ordens_servico o where o.plano_manutencao_id=plano.id and o.inicio_previsto::date=plano.proxima_execucao) then
      insert into public.ordens_servico(organizacao_id,plano_manutencao_id,ativo_id,prestador_id,executor_id,titulo,natureza,status,inicio_previsto,fim_previsto,criado_por)
      values(plano.organizacao_id,plano.id,plano.ativo_id,plano.prestador_id,plano.executor_id,plano.nome,'Preventiva','Planejada',plano.proxima_execucao,plano.proxima_execucao,coalesce(plano.criado_por,(select id from public.perfis where organizacao_id=plano.organizacao_id and papel='gestor' and ativo limit 1)));
      total:=total+1;
    end if;
    update public.planos_manutencao set proxima_execucao=proxima_execucao+periodicidade_dias where id=plano.id;
  end loop;
  return total;
end $$;

-- Quando pg_cron estiver disponível no projeto, agenda a geração diária sem duplicar jobs.
do $$ begin
  if to_regnamespace('cron') is not null and not exists(select 1 from cron.job where jobname='cw-os-programadas') then
    perform cron.schedule('cw-os-programadas','15 3 * * *','select public.cw_gerar_os_programadas(current_date)');
  end if;
exception when insufficient_privilege or undefined_table or undefined_function then null;
end $$;

