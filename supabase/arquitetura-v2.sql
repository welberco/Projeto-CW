create or replace function public.cw_proximo_codigo(p_org uuid,p_entidade text,p_data date default current_date)
returns text language plpgsql security definer set search_path=public as $$
declare n integer; v_ano integer:=extract(year from p_data);
begin
  if p_entidade not in ('SOL','OS','EQP') then raise exception 'Entidade inválida'; end if;
  insert into public.cw_sequencias(organizacao_id,ano,entidade,ultimo_numero)
  values(p_org,v_ano,p_entidade,1)
  on conflict(organizacao_id,ano,entidade) do update set ultimo_numero=public.cw_sequencias.ultimo_numero+1
  returning ultimo_numero into n;
  return case when p_entidade='EQP' then format('EQP-%s',lpad(n::text,4,'0'))
    else format('%s-%s-%s',p_entidade,v_ano,lpad(n::text,3,'0')) end;
end $$;

create or replace function public.cw_preparar_solicitacao_v2() returns trigger
language plpgsql security definer set search_path=public as $$
begin
  if new.codigo_solicitacao is null then new.codigo_solicitacao:=public.cw_proximo_codigo(new.organizacao_id,'SOL',coalesce(new.criado_em,now())::date); end if;
  return new;
end $$;
drop trigger if exists cw_preparar_solicitacao_v2 on public.demandas;
create trigger cw_preparar_solicitacao_v2 before insert on public.demandas
for each row execute function public.cw_preparar_solicitacao_v2();

