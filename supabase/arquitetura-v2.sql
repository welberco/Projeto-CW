  values(p_organizacao_id,trim(p_titulo),'Manutenção',trim(p_local),case when public.tem_permissao_usuario('solicitacao_alterar_status') then coalesce(nullif(trim(p_prioridade),''),'A definir') else 'A definir' end,
    case when public.tem_permissao_usuario('solicitacao_alterar_status') then nullif(trim(p_responsavel),'') end,status_inicial,
