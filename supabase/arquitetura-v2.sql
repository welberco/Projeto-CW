      and p_papel in ('auxiliar','tecnico','usuario_padrao')
      and (p_usuario is null or exists(select 1 from public.perfis where id=p_usuario and organizacao_id=p_org and papel in ('auxiliar','tecnico','usuario_padrao'))))
